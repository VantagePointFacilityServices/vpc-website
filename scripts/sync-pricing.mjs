#!/usr/bin/env node
// Copies the vpos pricing data file into the Worker and generates the classic
// script the site reads (window.VPC_PRICING). Both carry the vpos source_commit.
// Usage: node scripts/sync-pricing.mjs [path-to-vpos]   (default ../vpos)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SPEC_REL = 'residential/docs/specs/residential-pricing.json';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export function sync(vposArg = '../vpos', outRoot = root) {
  const vpos = resolve(root, vposArg);
  const src = join(vpos, SPEC_REL);
  if (!existsSync(src)) throw new Error(`Pricing file not found: ${src}`);
  const data = JSON.parse(readFileSync(src, 'utf8'));
  let commit = 'unknown';
  try {
    commit = execFileSync('git', ['-C', vpos, 'log', '-1', '--format=%H', '--', SPEC_REL], { encoding: 'utf8' }).trim() || 'unknown';
  } catch { /* not a git checkout */ }
  const out = { source_commit: commit, ...data };
  const json = JSON.stringify(out, null, 2) + '\n';
  writeFileSync(join(outRoot, 'worker/pricing-data.json'), json);
  writeFileSync(
    join(outRoot, 'site/assets/js/pricing-data.js'),
    `// Generated by scripts/sync-pricing.mjs from vpos ${SPEC_REL}. Do not edit.\nwindow.VPC_PRICING = ${JSON.stringify(out, null, 2)};\n`,
  );
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const d = sync(process.argv[2]);
    console.log(`Synced pricing ${d.version} (vpos ${d.source_commit})`);
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
